"""
KafkaSimpleCdkStack

The smallest, most readable "Apache Kafka on EC2, not MSK" example -- optimized
for a learner reading the code top-to-bottom, not for HA or production security
posture. One EC2 instance, one Kafka broker, KRaft mode (no Zookeeper).

- Uses the AWS account's existing DEFAULT VPC (via a live `ec2.Vpc.from_lookup`
  lookup at synth time, cached into cdk.context.json) -- no custom VPC, subnet,
  internet gateway, or route table is created. This is the #1 simplification
  vs. a from-scratch-VPC design, and it's also the one genuine difference
  worth calling out: unlike CloudFormation (which has no live-account-lookup
  capability at template-authoring time and must take VpcId/SubnetId as
  Parameters instead), CDK can just ask the account "what's my default VPC"
  right here, which is why `cdk synth` for this stack needs real AWS
  credentials.
- 1 security group: ingress TCP 9092 from 0.0.0.0/0 (wide open -- fine for a
  disposable learning example, but scope this to a specific CIDR, e.g. your
  own IP, before using this for anything beyond a throwaway test), no SSH
  ingress, egress all.
- 1 IAM role (AmazonSSMManagedInstanceCore + read on the broker credentials
  secret) + instance profile -- SSM is the only access path, no SSH key pair
  anywhere in this stack.
- 1 Secrets Manager secret, created AUTOMATICALLY by this stack with a
  randomly generated password (no password is ever written in source, in
  cdk.context.json, or in the synthesized template -- CloudFormation asks
  Secrets Manager to generate it at deploy time). The broker reads it at boot
  via the instance role and uses it as its SASL/SCRAM credential, so the
  client listener on 9092 is authenticated rather than anonymous PLAINTEXT.
- 1 t3.small EC2 instance, single Kafka broker running in combined
  broker+controller KRaft mode (it is its own and only quorum voter).
"""

import json

from aws_cdk import (
    CfnOutput,
    RemovalPolicy,
    Stack,
    Tags,
    aws_ec2 as ec2,
    aws_iam as iam,
    aws_secretsmanager as secretsmanager,
)
from constructs import Construct

# ---------------------------------------------------------------------------
# Fixed spec values -- identical across all three IaC implementations.
# ---------------------------------------------------------------------------
NAME_PREFIX = "kafka-simple-cdk"

KAFKA_VERSION = "4.3.1"
KAFKA_SCALA_ARTIFACT = f"kafka_2.13-{KAFKA_VERSION}"
KAFKA_DOWNLOAD_URL = f"https://downloads.apache.org/kafka/{KAFKA_VERSION}/{KAFKA_SCALA_ARTIFACT}.tgz"
KRAFT_CLUSTER_ID = "zsvUnJ-LSWW-5vb3PEALHQ"

AL2023_AMI_SSM_PARAM = "/aws/service/ami-amazon-linux-latest/al2023-ami-kernel-default-x86_64"

SSM_CONNECT_NOTE = (
    "Connect via SSM: aws ssm start-session --target <instance-id> "
    "(no SSH key pair exists in this design)"
)

# ---------------------------------------------------------------------------
# Secrets Manager -- broker SASL/SCRAM credentials.
#
# The secret is created by this stack and its password is GENERATED by Secrets
# Manager at deploy time, so no credential material exists in this repo or in
# the synthesized CloudFormation template. The username is a fixed, non-secret
# template field; only `password` is generated.
# ---------------------------------------------------------------------------
SECRET_NAME = f"{NAME_PREFIX}-broker-credentials"
SASL_USERNAME = "kafka-admin"
SASL_MECHANISM = "SCRAM-SHA-512"

# Single-node bootstrap script -- every value is a literal since there's only
# one node (no NODE_ID / controller-quorum-voters-list parameterization to
# worry about, unlike a multi-broker design). Two things are resolved at boot
# rather than baked in here:
#   - the instance's own private IP (via IMDSv2), not known until launch;
#   - the SASL password, pulled from Secrets Manager with the instance role.
#
# This is a function rather than a module-level constant because it needs the
# secret's ARN and the stack's region, which are CDK tokens resolved during
# synth. `ec2.UserData.custom()` handles tokens fine -- they become an
# Fn::Join in the template.
def build_user_data(secret_arn: str, region: str) -> str:
    return f"""#!/bin/bash
set -euxo pipefail

# 1. Packages (jq parses the Secrets Manager JSON payload; the AWS CLI v2 is
#    already present on AL2023)
dnf install -y java-17-amazon-corretto-headless wget tar jq

# 2. Dedicated unprivileged OS user
if ! id kafka &>/dev/null; then
  useradd -r -m -d /home/kafka kafka
fi

# 3. Data dir
mkdir -p /var/lib/kafka/data
chown -R kafka:kafka /var/lib/kafka/data

# 4. Download + extract Kafka {KAFKA_VERSION} to /opt/kafka
cd /opt
wget -q "{KAFKA_DOWNLOAD_URL}"
tar -xzf "{KAFKA_SCALA_ARTIFACT}.tgz"
rm -f "{KAFKA_SCALA_ARTIFACT}.tgz"
rm -rf /opt/kafka
mv "/opt/{KAFKA_SCALA_ARTIFACT}" /opt/kafka
chown -R kafka:kafka /opt/kafka

# 5. Resolve this instance's own private IP live via IMDSv2 (single node, but
#    still not hardcoded -- it looks up its own address dynamically like
#    everything else)
TOKEN=$(curl -sS -X PUT "http://169.254.169.254/latest/api/token" -H "X-aws-ec2-metadata-token-ttl-seconds: 21600")
OWN_PRIVATE_IP=$(curl -sS -H "X-aws-ec2-metadata-token: $TOKEN" http://169.254.169.254/latest/meta-data/local-ipv4)

# 6. Pull the broker's SASL credentials from Secrets Manager using the
#    instance role. `set +x` first: with `set -x` still on, the shell would
#    echo the password straight into /var/log/cloud-init-output.log, which
#    would defeat the entire point of putting it in Secrets Manager.
set +x
SECRET_JSON=$(aws secretsmanager get-secret-value \\
  --secret-id "{secret_arn}" \\
  --region "{region}" \\
  --query SecretString \\
  --output text)
KAFKA_USERNAME=$(printf '%s' "$SECRET_JSON" | jq -r '.username')
KAFKA_PASSWORD=$(printf '%s' "$SECRET_JSON" | jq -r '.password')
unset SECRET_JSON
if [ -z "$KAFKA_USERNAME" ] || [ -z "$KAFKA_PASSWORD" ] || [ "$KAFKA_PASSWORD" = "null" ]; then
  echo "FATAL: could not read username/password from the broker credentials secret" >&2
  exit 1
fi

# 7. Write server.properties -- single-node KRaft, combined broker+controller,
#    this node is its own and only quorum voter.
#
#    The client-facing listener on 9092 is SASL_PLAINTEXT with SCRAM-SHA-512,
#    authenticated with the Secrets Manager credential. The CONTROLLER
#    listener on 9093 stays PLAINTEXT: it is the node talking to itself for
#    the KRaft quorum and is not reachable from outside (no security-group
#    rule opens 9093).
#
#    Created with a restrictive umask and chmod 600 because this file now
#    contains the password in its JAAS config line.
umask 077
cat > /opt/kafka/config/server.properties <<EOF
process.roles=broker,controller
node.id=1
controller.quorum.voters=1@$OWN_PRIVATE_IP:9093
listeners=SASL_PLAINTEXT://0.0.0.0:9092,CONTROLLER://0.0.0.0:9093
inter.broker.listener.name=SASL_PLAINTEXT
advertised.listeners=SASL_PLAINTEXT://$OWN_PRIVATE_IP:9092
controller.listener.names=CONTROLLER
listener.security.protocol.map=CONTROLLER:PLAINTEXT,SASL_PLAINTEXT:SASL_PLAINTEXT
sasl.enabled.mechanisms={SASL_MECHANISM}
sasl.mechanism.inter.broker.protocol={SASL_MECHANISM}
listener.name.sasl_plaintext.scram-sha-512.sasl.jaas.config=org.apache.kafka.common.security.scram.ScramLoginModule required username="$KAFKA_USERNAME" password="$KAFKA_PASSWORD";
super.users=User:$KAFKA_USERNAME
log.dirs=/var/lib/kafka/data
num.partitions=1
default.replication.factor=1
offsets.topic.replication.factor=1
transaction.state.log.replication.factor=1
transaction.state.log.min.isr=1
EOF

# 8. Drop a ready-to-use client config next to it, so the bundled CLI tools
#    (kafka-topics.sh, kafka-console-producer.sh, ...) can authenticate with
#    --command-config / --producer.config / --consumer.config.
cat > /opt/kafka/config/client.properties <<EOF
security.protocol=SASL_PLAINTEXT
sasl.mechanism={SASL_MECHANISM}
sasl.jaas.config=org.apache.kafka.common.security.scram.ScramLoginModule required username="$KAFKA_USERNAME" password="$KAFKA_PASSWORD";
EOF
umask 022

chown kafka:kafka /opt/kafka/config/server.properties /opt/kafka/config/client.properties
chmod 600 /opt/kafka/config/server.properties /opt/kafka/config/client.properties

# 9. Format storage (idempotent across reboots).
#
#    --add-scram seeds the SCRAM credential into the KRaft metadata log at
#    format time. This is the KRaft-native way to bootstrap the very first
#    SASL user -- without it there would be no credential to authenticate
#    with, and no authenticated path over which to create one.
#
#    --ignore-formatted makes reboots a no-op; it also means --add-scram only
#    takes effect on the first boot, when the log dir is still empty.
sudo -u kafka /opt/kafka/bin/kafka-storage.sh format \\
  --cluster-id {KRAFT_CLUSTER_ID} \\
  --config /opt/kafka/config/server.properties \\
  --add-scram "{SASL_MECHANISM}=[name=$KAFKA_USERNAME,password=$KAFKA_PASSWORD]" \\
  --ignore-formatted

unset KAFKA_PASSWORD
set -x

# 10. systemd unit
cat > /etc/systemd/system/kafka.service <<'UNIT'
[Unit]
Description=Apache Kafka (KRaft, single node)
After=network.target

[Service]
Type=simple
User=kafka
Environment=JAVA_HOME=/usr/lib/jvm/java-17-amazon-corretto
ExecStart=/opt/kafka/bin/kafka-server-start.sh /opt/kafka/config/server.properties
Restart=on-failure
RestartSec=5
LimitNOFILE=65536

[Install]
WantedBy=multi-user.target
UNIT

# 11. Enable + start
systemctl daemon-reload
systemctl enable --now kafka
"""


class KafkaSimpleCdkStack(Stack):
    def __init__(self, scope: Construct, construct_id: str, **kwargs) -> None:
        super().__init__(scope, construct_id, **kwargs)

        # Common tags on every taggable resource in this stack.
        Tags.of(self).add("Project", "kafka-simple-no-msk")
        Tags.of(self).add("Iac", "cdk")

        # -------------------------------------------------------------
        # Networking -- the account's existing DEFAULT VPC, looked up live.
        # No custom VPC/subnet/IGW/route table is created anywhere.
        # -------------------------------------------------------------
        vpc = ec2.Vpc.from_lookup(self, "DefaultVpc", is_default=True)

        # Pick the first public subnet for the instance.
        subnet = vpc.public_subnets[0]

        # -------------------------------------------------------------
        # Security group -- ingress 9092 from anywhere, no SSH
        # -------------------------------------------------------------
        sg = ec2.SecurityGroup(
            self, "KafkaBrokerSg",
            vpc=vpc,
            description=(
                "Kafka client/data-plane traffic (SASL-authenticated) for the "
                "kafka-simple learning example"
            ),
            allow_all_outbound=True,
            security_group_name=f"{NAME_PREFIX}-sg",
        )
        Tags.of(sg).add("Name", f"{NAME_PREFIX}-sg")

        sg.add_ingress_rule(
            peer=ec2.Peer.any_ipv4(),
            connection=ec2.Port.tcp(9092),
            # Wide open (0.0.0.0/0) for learning-example simplicity. The
            # listener behind it is now SASL-authenticated, so reaching the
            # port is no longer the same as being able to use the broker --
            # but still scope this to a specific CIDR (e.g. your own IP) for
            # anything beyond a throwaway test.
            description=(
                "Kafka client/data plane (SASL_PLAINTEXT) -- wide open for "
                "learning-example simplicity; scope to a specific CIDR (e.g. "
                "your own IP) for anything beyond a throwaway test"
            ),
        )
        # No SSH ingress rule -- access is via SSM Session Manager only.

        # -------------------------------------------------------------
        # Secrets Manager -- broker SASL/SCRAM credentials, created here.
        #
        # `generate_secret_string` is what makes this automatic: CDK emits a
        # GenerateSecretString block, and CloudFormation has Secrets Manager
        # mint the password during deploy. The password therefore never exists
        # in this repo, in cdk.context.json, or in the synthesized template --
        # only the non-secret username template does.
        #
        # exclude_punctuation=True keeps the password alphanumeric, which
        # sidesteps three separate quoting layers it has to survive on the
        # instance: the shell, the Kafka properties file, and the JAAS config
        # line. At 32 characters that is still ~190 bits of entropy.
        # -------------------------------------------------------------
        secret = secretsmanager.Secret(
            self, "KafkaBrokerCredentials",
            secret_name=SECRET_NAME,
            description=(
                f"SASL/{SASL_MECHANISM} credentials for the {NAME_PREFIX} broker "
                "-- password auto-generated by Secrets Manager at deploy time"
            ),
            generate_secret_string=secretsmanager.SecretStringGenerator(
                secret_string_template=json.dumps({"username": SASL_USERNAME}),
                generate_string_key="password",
                password_length=32,
                exclude_punctuation=True,
            ),
            # Disposable learning stack: `cdk destroy` should take the secret
            # with it. Note Secrets Manager still applies a 30-day recovery
            # window, so redeploying under the same name inside that window
            # needs a force-delete first -- see the README.
            removal_policy=RemovalPolicy.DESTROY,
        )

        # -------------------------------------------------------------
        # IAM role + instance profile -- SSM only, no SSH
        # -------------------------------------------------------------
        role = iam.Role(
            self, "KafkaEc2Role",
            role_name=f"{NAME_PREFIX}-ec2-role",
            assumed_by=iam.ServicePrincipal("ec2.amazonaws.com"),
            managed_policies=[
                iam.ManagedPolicy.from_aws_managed_policy_name("AmazonSSMManagedInstanceCore"),
            ],
        )

        # The only privilege the broker gets beyond SSM: read THIS one secret.
        # grant_read scopes secretsmanager:GetSecretValue to this secret's ARN
        # rather than handing the instance a blanket secretsmanager:* .
        secret.grant_read(role)

        instance_profile = iam.InstanceProfile(
            self, "KafkaInstanceProfile",
            instance_profile_name=f"{NAME_PREFIX}-instance-profile",
            role=role,
        )

        # -------------------------------------------------------------
        # AMI -- latest AL2023 x86_64 resolved via SSM dynamic reference
        # (resolved at deploy time by CloudFormation, not at synth time)
        # -------------------------------------------------------------
        machine_image = ec2.MachineImage.from_ssm_parameter(
            AL2023_AMI_SSM_PARAM,
            os=ec2.OperatingSystemType.LINUX,
        )

        # -------------------------------------------------------------
        # Compute -- exactly 1 t3.small instance, single Kafka broker
        # -------------------------------------------------------------
        instance = ec2.Instance(
            self, "KafkaBroker",
            instance_type=ec2.InstanceType("t3.small"),
            machine_image=machine_image,
            vpc=vpc,
            vpc_subnets=ec2.SubnetSelection(subnets=[subnet]),
            associate_public_ip_address=True,
            security_group=sg,
            instance_profile=instance_profile,
            instance_name="kafka-simple-broker",
            user_data=ec2.UserData.custom(
                build_user_data(secret_arn=secret.secret_arn, region=self.region),
            ),
            block_devices=[
                ec2.BlockDevice(
                    device_name="/dev/xvda",
                    volume=ec2.BlockDeviceVolume.ebs(
                        20,
                        volume_type=ec2.EbsDeviceVolumeType.GP3,
                        delete_on_termination=True,
                    ),
                ),
            ],
        )

        # -------------------------------------------------------------
        # Outputs
        # -------------------------------------------------------------
        CfnOutput(
            self, "InstanceId",
            value=instance.instance_id,
            description=f"kafka-simple-broker instance ID -- {SSM_CONNECT_NOTE}",
        )
        CfnOutput(
            self, "PublicIp",
            value=instance.instance_public_ip,
            description="kafka-simple-broker public IP (for external producer/consumer testing)",
        )
        CfnOutput(
            self, "PrivateIp",
            value=instance.instance_private_ip,
            description="kafka-simple-broker private IP",
        )
        CfnOutput(
            self, "SecurityGroupId",
            value=sg.security_group_id,
            description=f"{NAME_PREFIX}-sg security group ID",
        )
        CfnOutput(
            self, "BrokerCredentialsSecretArn",
            value=secret.secret_arn,
            description=(
                "ARN of the auto-created Secrets Manager secret holding the broker's "
                f"SASL/{SASL_MECHANISM} username and generated password"
            ),
        )
        CfnOutput(
            self, "BrokerCredentialsSecretName",
            value=secret.secret_name,
            description=(
                "Name of the broker credentials secret -- read it with: "
                f"aws secretsmanager get-secret-value --secret-id {SECRET_NAME} "
                "--query SecretString --output text"
            ),
        )
        CfnOutput(
            self, "ClientSecurityProtocol",
            value=f"SASL_PLAINTEXT / {SASL_MECHANISM}",
            description=(
                "Clients must authenticate on port 9092 with the credentials in the "
                "secret above; anonymous PLAINTEXT connections are rejected"
            ),
        )
